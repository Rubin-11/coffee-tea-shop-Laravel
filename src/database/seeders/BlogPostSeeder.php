<?php

namespace Database\Seeders;

use App\Models\BlogPost;
use App\Models\User;
use Illuminate\Database\Console\Seeds\WithoutModelEvents;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;

/**
 * Seeder для заполнения таблицы статей блога
 *
 * Создает 10-12 статей блога по темам:
 * - Здоровое питание
 * - Рецепты с кофе
 * - Гид по выбору кофе
 * - История происхождения
 * - Новости компании
 * - Советы бариста
 * - Культура чаепития
 *
 * Статьи привязываются к существующим пользователям (администраторам)
 * и имеют разное количество просмотров (50-500)
 */
class BlogPostSeeder extends Seeder
{
    use WithoutModelEvents;

    /**
     * Запуск seeder'а
     *
     * Создает 10 опубликованных статей с реалистичным контентом
     */
    public function run(): void
    {
        $this->command->info('📝 Создание статей блога...');

        // Получаем администраторов или любых пользователей для привязки статей
        $authors = User::where('is_admin', true)->get();

        // Если администраторов нет, берем любых пользователей
        if ($authors->isEmpty()) {
            $authors = User::limit(3)->get();
        }

        // Если пользователей вообще нет, создаем одного для статей
        if ($authors->isEmpty()) {
            $this->command->warn('⚠️  Пользователи не найдены. Создаем автора для статей...');
            $authors = collect([
                User::create([
                    'first_name' => 'Автор',
                    'last_name' => 'Блога',
                    'email' => 'blog-author@coffee-shop.ru',
                    'password' => bcrypt('password'),
                    'is_admin' => true,
                    'is_active' => true,
                ]),
            ]);
        }

        // Создаем популярные статьи о кофе (3 штуки)
        $this->command->comment('  → Создание популярных статей о кофе...');
        BlogPost::factory()
            ->count(3)
            ->coffee()
            ->popular()
            ->create([
                'author_id' => $authors->random()->id,
            ]);

        // Создаем статьи о чае (2 штуки)
        $this->command->comment('  → Создание статей о чае...');
        BlogPost::factory()
            ->count(2)
            ->tea()
            ->published()
            ->create([
                'author_id' => $authors->random()->id,
            ]);

        // Создаем недавние статьи о кофе (3 штуки)
        $this->command->comment('  → Создание недавних статей...');
        BlogPost::factory()
            ->count(3)
            ->coffee()
            ->recent()
            ->create([
                'author_id' => $authors->random()->id,
            ]);

        // Создаем обычные опубликованные статьи (2 штуки)
        $this->command->comment('  → Создание обычных статей...');
        BlogPost::factory()
            ->count(2)
            ->published()
            ->create([
                'author_id' => $authors->random()->id,
            ]);

        // Создаем 1 черновик для демонстрации функционала
        $this->command->comment('  → Создание черновика...');
        BlogPost::factory()
            ->draft()
            ->create([
                'author_id' => $authors->random()->id,
                'title' => 'Новая статья о секретах приготовления капучино',
                'category' => 'Советы бариста',
            ]);

        // Создаем специальные статьи с конкретным контентом
        $this->createCustomArticles($authors);

        $totalPosts = BlogPost::count();
        $publishedPosts = BlogPost::where('is_published', true)->count();
        $draftPosts = BlogPost::where('is_published', false)->count();

        $this->command->info("  ✅ Создано статей блога: {$totalPosts}");
        $this->command->info("     • Опубликовано: {$publishedPosts}");
        $this->command->info("     • Черновиков: {$draftPosts}");
        $this->command->newLine();
    }

    /**
     * Создание специальных статей с конкретным контентом
     *
     * Эти статьи имеют определенные темы и контент для демонстрации
     * возможностей блога
     *
     * @param  Collection  $authors
     */
    private function createCustomArticles($authors): void
    {
        // Статья о здоровом питании (как в макете)
        BlogPost::create([
            'title' => 'Кофе и здоровье: польза и вред кофеина',
            'slug' => Str::slug('Кофе и здоровье: польза и вред кофеина'),
            'excerpt' => 'Разбираемся, сколько кофе можно пить в день без вреда для здоровья, какие витамины содержатся в кофейных зернах и почему кофе может быть полезным напитком.',
            'content' => $this->getHealthyDrinkingContent(),
            'featured_image' => 'blog/health-coffee.jpg',
            'author_id' => $authors->random()->id,
            'category' => 'Здоровое питание',
            'views_count' => 1247,
            'is_published' => true,
            'published_at' => now()->subMonths(2),
            'meta_title' => 'Кофе и здоровье: польза и вред кофеина | Блог Coffee-Tea Shop',
            'meta_description' => 'Научные факты о влиянии кофе на здоровье. Польза и вред кофеина, рекомендации по употреблению.',
        ]);

        // Статья о происхождении кофе
        BlogPost::create([
            'title' => 'История кофе: от Эфиопии до наших дней',
            'slug' => Str::slug('История кофе: от Эфиопии до наших дней'),
            'excerpt' => 'Увлекательная история о том, как кофе из дикорастущего растения в Эфиопии превратился в один из самых популярных напитков в мире.',
            'content' => $this->getCoffeeHistoryContent(),
            'featured_image' => 'blog/coffee-history.jpg',
            'author_id' => $authors->random()->id,
            'category' => 'История происхождения',
            'views_count' => 856,
            'is_published' => true,
            'published_at' => now()->subMonths(3),
            'meta_title' => 'История кофе: от Эфиопии до наших дней | Coffee-Tea Shop',
            'meta_description' => 'Узнайте историю происхождения кофе, легенды об открытии кофейных зерен и путь кофе по миру.',
        ]);
    }

    /**
     * Контент статьи о здоровом питании
     */
    private function getHealthyDrinkingContent(): string
    {
        return '
            <h2>Польза кофе для здоровья</h2>
            <p>Кофе — это не просто вкусный напиток для пробуждения. Многочисленные исследования показывают, что умеренное потребление кофе может принести пользу здоровью. В кофейных зернах содержатся антиоксиданты, которые помогают бороться со свободными радикалами и замедляют процесс старения клеток.</p>
            
            <p>Кофеин, содержащийся в кофе, стимулирует центральную нервную систему, улучшает концентрацию внимания и повышает работоспособность. Именно поэтому многие люди не могут представить свое утро без чашки ароматного кофе.</p>
            
            <h2>Сколько кофе можно пить в день?</h2>
            <p>Согласно рекомендациям Всемирной организации здравоохранения, безопасная суточная доза кофеина составляет 400 мг, что эквивалентно примерно 3-4 чашкам кофе. Однако индивидуальная переносимость кофеина может различаться.</p>
            
            <p>Важно помнить, что чрезмерное употребление кофе может привести к бессоннице, тревожности, учащенному сердцебиению и повышению артериального давления. Поэтому рекомендуется не превышать рекомендуемую дозу и прислушиваться к своему организму.</p>
            
            <h2>Витамины и минералы в кофе</h2>
            <p>Натуральный кофе содержит множество полезных веществ:</p>
            <ul>
                <li><strong>Витамин B2 (рибофлавин)</strong> — важен для обмена веществ</li>
                <li><strong>Витамин B3 (ниацин)</strong> — поддерживает здоровье кожи и нервной системы</li>
                <li><strong>Магний и калий</strong> — необходимы для нормальной работы сердца</li>
                <li><strong>Антиоксиданты</strong> — защищают клетки от повреждений</li>
            </ul>
            
            <h2>Когда стоит ограничить употребление кофе?</h2>
            <p>Несмотря на многочисленные преимущества, есть ситуации, когда стоит ограничить или исключить кофе из рациона:</p>
            <ul>
                <li>Беременность и кормление грудью</li>
                <li>Заболевания желудочно-кишечного тракта</li>
                <li>Гипертония и сердечно-сосудистые заболевания</li>
                <li>Повышенная тревожность и бессонница</li>
            </ul>
            
            <p>В заключение хочется сказать, что кофе может быть частью здорового образа жизни, если употреблять его в меру и прислушиваться к сигналам своего организма. Наслаждайтесь любимым напитком и будьте здоровы!</p>
        ';
    }

    /**
     * Контент статьи об истории кофе
     */
    private function getCoffeeHistoryContent(): string
    {
        return '
            <h2>Легенда об открытии кофе</h2>
            <p>История кофе окутана множеством легенд и преданий. Самая известная из них рассказывает о пастухе по имени Калди из Эфиопии, который в IX веке заметил странное поведение своих коз. После того как животные ели ягоды с определенного дерева, они становились необычайно энергичными и не могли уснуть ночью.</p>
            
            <p>Заинтригованный пастух попробовал ягоды сам и ощутил прилив бодрости. Он рассказал об этом открытии местным монахам, которые начали использовать отвар из этих ягод, чтобы не засыпать во время длительных молитв. Так началось распространение кофе по всему миру.</p>
            
            <h2>Путь кофе с Востока на Запад</h2>
            <p>Первые письменные упоминания о кофе как напитке датируются XV веком. Кофе начали выращивать в Йемене, где монахи-суфии использовали его для поддержания бодрости во время ночных молитв. Оттуда кофе распространился по всему арабскому миру.</p>
            
            <p>В XVI веке кофе достиг Османской империи, где в Константинополе (современный Стамбул) открылись первые кофейни. Эти заведения быстро стали центрами общественной жизни, где люди собирались, чтобы обсудить новости, поиграть в шахматы и насладиться ароматным напитком.</p>
            
            <h2>Кофе в Европе</h2>
            <p>В Европу кофе попал в XVII веке через венецианских торговцев. Сначала церковь относилась к новому напитку с подозрением, называя его "горьким изобретением сатаны". Однако после того как Папа Климент VIII попробовал кофе и одобрил его, напиток быстро завоевал популярность.</p>
            
            <p>Первые европейские кофейни открылись в Венеции (1645), Лондоне (1652) и Париже (1672). Они стали местами встреч интеллектуалов, писателей и политиков. Многие исторические решения и революционные идеи рождались именно в кофейнях.</p>
            
            <h2>Колониальная эпоха и распространение кофе</h2>
            <p>В XVII-XVIII веках европейские колониальные державы начали выращивать кофе в своих тропических колониях. Голландцы первыми вывезли кофейные деревья из Йемена и начали культивировать их на острове Ява (современная Индонезия).</p>
            
            <p>Французы привезли кофе на Карибские острова, откуда он попал в Южную Америку. Сегодня Бразилия является крупнейшим производителем кофе в мире, что стало возможным благодаря этому историческому пути.</p>
            
            <h2>Кофе в современном мире</h2>
            <p>Сегодня кофе — это второй по популярности напиток в мире после воды и второй по объему торговли товар после нефти. Кофейная индустрия обеспечивает работой миллионы людей по всему миру — от фермеров в Эфиопии и Колумбии до бариста в модных кофейнях Токио и Нью-Йорка.</p>
            
            <p>История кофе — это история глобализации, культурного обмена и человеческой изобретательности. От дикорастущих кустов в эфиопских горах до сложных эспрессо-машин в современных кофейнях — кофе прошел невероятный путь, оставаясь при этом любимым напитком миллиардов людей.</p>
        ';
    }
}
